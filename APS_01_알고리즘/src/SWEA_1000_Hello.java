import java.util.Scanner;

public class SWEA_1000_Hello {
	public static void main(String[] args) {
		Scanner sc = new Scanner(System.in);
		int T = sc.nextInt(); // 테스트케이스 수
		for (int tc = 1; tc <= T; tc++) {
			int ans = 0;

			// 출력 형태 #tc ans
			System.out.println("#" + tc + " " + ans);
		} // tc for문

	}// main
}
